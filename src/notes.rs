//! Markdown note generation. Notes are views of SQLite state: only the region
//! between the sb markers is rewritten; anything the user writes outside it
//! is preserved. Entities stay `dirty` until their note is written, so an
//! interruption between DB commit and file write is repaired on the next run.

use crate::brain::Brain;
use crate::util::{atomic_write, safe_filename};
use anyhow::Result;
use rusqlite::{Connection, params};
use std::path::PathBuf;

pub const BEGIN: &str = "<!-- sb:begin - generated by second-brain; edits inside this block are overwritten -->";
pub const END: &str = "<!-- sb:end -->";

pub fn note_path(brain: &Brain, kind: &str, name: &str) -> PathBuf {
    let dir = if kind == "project" || kind == "goal" { "projects" } else { "knowledge" };
    brain.vault().join(dir).join(format!("{}.md", safe_filename(name)))
}

/// Write `generated` into the managed region of `path`, creating the file if needed.
/// Returns whether the file changed.
pub fn write_region(path: &std::path::Path, frontmatter: &str, title: &str, generated: &str) -> Result<bool> {
    let region = format!("{BEGIN}\n{}\n{END}", generated.trim_end());
    let old = std::fs::read_to_string(path).ok();
    let new = match &old {
        Some(text) => match (text.find("<!-- sb:begin"), text.find(END)) {
            (Some(a), Some(b)) if b > a => format!("{}{}{}", &text[..a], region, &text[b + END.len()..]),
            _ => format!("{}\n\n{}\n", text.trim_end(), region),
        },
        None => format!("---\n{frontmatter}---\n# {title}\n\n{region}\n"),
    };
    if old.as_deref() == Some(new.as_str()) {
        return Ok(false);
    }
    atomic_write(path, &new)?;
    Ok(true)
}

fn source_link(conn: &Connection, block_id: Option<i64>) -> Result<String> {
    let Some(b) = block_id else { return Ok(String::new()) };
    let path: Option<String> = conn
        .query_row("SELECT s.path FROM blocks b JOIN sources s ON s.id=b.source_id WHERE b.id=?1", [b], |r| r.get(0))
        .ok();
    Ok(path
        .map(|p| {
            let stem = std::path::Path::new(&p).file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or(p);
            format!(" - [[{stem}]]")
        })
        .unwrap_or_default())
}

struct Mem {
    kind: String,
    content: String,
    epistemic: String,
    occurred_on: Option<String>,
    block_id: Option<i64>,
}

fn memories_for(conn: &Connection, entity: i64) -> Result<Vec<Mem>> {
    let mut st = conn.prepare(
        "SELECT m.kind, m.content, m.epistemic, m.occurred_on, m.block_id FROM memories m
         JOIN memory_entities me ON me.memory_id=m.id WHERE me.entity_id=?1 AND m.status='active'
         ORDER BY coalesce(m.occurred_on, m.recorded_at), m.id",
    )?;
    let rows = st
        .query_map([entity], |r| {
            Ok(Mem {
                kind: r.get(0)?,
                content: r.get(1)?,
                epistemic: r.get(2)?,
                occurred_on: r.get(3)?,
                block_id: r.get(4)?,
            })
        })?
        .collect::<rusqlite::Result<Vec<_>>>()?;
    Ok(rows)
}

/// (name, kind, relation, why, outgoing)
type Linked = (String, String, String, Option<String>, bool);

const TREE: [&str; 3] = ["in_area", "in_theme", "part_of"];

fn linked(conn: &Connection, entity: i64) -> Result<Vec<Linked>> {
    let mut st = conn.prepare(
        "SELECT e.name, e.kind, l.relation, l.why, l.src=?1 FROM links l JOIN entities e ON e.id = CASE WHEN l.src=?1 THEN l.dst ELSE l.src END
         WHERE (l.src=?1 OR l.dst=?1) AND e.status='active' ORDER BY e.kind, e.name",
    )?;
    let rows = st
        .query_map([entity], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?)))?
        .collect::<rusqlite::Result<Vec<_>>>()?;
    Ok(rows)
}

/// "[[Cybersecurity]] › [[Detection engineering]]" for an item, from its upward links.
fn breadcrumb(conn: &Connection, links: &[Linked]) -> Result<Option<String>> {
    let up: Vec<&Linked> = links.iter().filter(|l| l.4 && TREE.contains(&l.2.as_str())).collect();
    let Some(first) = up.first() else { return Ok(None) };
    if first.1 == "theme" && first.2 == "in_theme" {
        let parent: Option<String> = conn
            .query_row(
                "SELECT a.name FROM entities t JOIN links p ON p.src=t.id AND p.relation='part_of' JOIN entities a ON a.id=p.dst
                 WHERE t.name=?1 AND a.status='active' LIMIT 1",
                [&first.0],
                |r| r.get(0),
            )
            .ok();
        return Ok(Some(match parent {
            Some(a) => format!("[[{a}]] › [[{}]]", first.0),
            None => format!("[[{}]]", first.0),
        }));
    }
    Ok(Some(up.iter().map(|l| format!("[[{}]]", l.0)).collect::<Vec<_>>().join(" · ")))
}

fn render_entity(brain: &Brain, id: i64) -> Result<(PathBuf, String, String, String)> {
    let conn = &brain.conn;
    let (kind, name, summary, created): (String, String, Option<String>, String) =
        conn.query_row("SELECT kind, name, summary, created_at FROM entities WHERE id=?1", [id], |r| {
            Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?))
        })?;
    let mut g = String::new();
    if let Some(s) = summary.filter(|s| !s.is_empty()) {
        g.push_str(&format!("> {s}\n\n"));
    }
    let mems = memories_for(conn, id)?;
    let section = |g: &mut String, title: &str, kinds: &[&str], dated: bool| -> Result<()> {
        let sel: Vec<&Mem> = mems.iter().filter(|m| kinds.contains(&m.kind.as_str())).collect();
        if sel.is_empty() {
            return Ok(());
        }
        g.push_str(&format!("## {title}\n"));
        for m in sel {
            let date = if dated {
                m.occurred_on.as_deref().map(|d| format!("**{d}** ")).unwrap_or_default()
            } else {
                String::new()
            };
            let tag = match m.epistemic.as_str() {
                "hypothesis" if m.kind != "idea" => " _(hypothesis)_",
                "opinion" => " _(opinion)_",
                _ => "",
            };
            let src = source_link(conn, m.block_id)?;
            match crate::util::split_list(&m.content) {
                Some((intro, items)) => {
                    let head = if intro.is_empty() {
                        format!(
                            "{} {}",
                            items.len(),
                            if brain.cfg.language.starts_with("fr") { "éléments" } else { "items" }
                        )
                    } else {
                        intro
                    };
                    g.push_str(&format!("- {date}{head}{tag}{src}\n"));
                    for (k, it) in items.iter().enumerate() {
                        g.push_str(&format!("    {}. {it}\n", k + 1));
                    }
                }
                None => g.push_str(&format!("- {date}{}{tag}{src}\n", m.content)),
            }
        }
        g.push('\n');
        Ok(())
    };
    section(&mut g, "Goal", &["goal"], false)?;
    section(&mut g, "Key points", &["knowledge"], false)?;
    section(&mut g, "Ideas", &["idea"], false)?;
    section(&mut g, "To explore", &["resource"], false)?;

    if kind == "project" || kind == "goal" {
        let mut st = conn.prepare(
            "SELECT id, kind, title, status, due FROM tasks WHERE project_id=?1 AND status IN ('open','proposed')
             ORDER BY due IS NULL, due, priority",
        )?;
        let tasks: Vec<(i64, String, String, String, Option<String>)> = st
            .query_map([id], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?)))?
            .collect::<rusqlite::Result<_>>()?;
        if !tasks.is_empty() {
            g.push_str("## Open tasks & deadlines\n");
            for (tid, k, title, status, due) in tasks {
                let icon = if k == "deadline" {
                    "📅"
                } else if status == "proposed" {
                    "❔"
                } else {
                    "☐"
                };
                g.push_str(&format!(
                    "- {icon} {title}{} `#t{tid}`\n",
                    due.map(|d| format!(" - due {d}")).unwrap_or_default()
                ));
            }
            g.push('\n');
        }
        let done: i64 =
            conn.query_row("SELECT count(*) FROM tasks WHERE project_id=?1 AND status='done'", [id], |r| r.get(0))?;
        if done > 0 {
            g.push_str(&format!("_{done} task(s) completed._\n\n"));
        }
    }
    section(&mut g, "Decisions", &["decision"], true)?;
    section(&mut g, "Log", &["episodic"], true)?;

    let links = linked(conn, id)?;
    if let Some(bc) = breadcrumb(conn, &links)? {
        g.push_str(&format!("**Theme:** {bc}\n\n"));
    }
    let item = |l: &Linked| format!("- [[{}]]{}\n", l.0, l.3.as_ref().map(|w| format!(" - {w}")).unwrap_or_default());
    // Children of a hub: themes of a grand theme, items of a theme/area.
    let children: Vec<&Linked> = links.iter().filter(|l| !l.4 && TREE.contains(&l.2.as_str())).collect();
    let themes: Vec<&&Linked> = children.iter().filter(|l| l.1 == "theme").collect();
    let items: Vec<&&Linked> = children.iter().filter(|l| l.1 != "theme").collect();
    if !themes.is_empty() {
        g.push_str("## Themes\n");
        themes.iter().for_each(|l| g.push_str(&item(l)));
        g.push('\n');
    }
    if !items.is_empty() {
        g.push_str(if kind == "theme" { "## In this theme\n" } else { "## In this area\n" });
        items.iter().for_each(|l| g.push_str(&item(l)));
        g.push('\n');
    }
    let conns: Vec<&Linked> = links.iter().filter(|l| !TREE.contains(&l.2.as_str())).collect();
    if !conns.is_empty() {
        g.push_str("## Connections\n");
        conns.iter().for_each(|l| g.push_str(&item(l)));
        g.push('\n');
    }
    if g.trim().is_empty() {
        g.push_str("_No details yet._\n");
    }
    let fm = format!("type: {kind}\nsb_id: {id}\ncreated: {}\n", &created[..10.min(created.len())]);
    Ok((note_path(brain, &kind, &name), fm, name, g))
}

fn render_profile(brain: &Brain) -> Result<String> {
    let mut st = brain.conn.prepare(
        "SELECT key, content, occurred_on, block_id FROM memories WHERE kind='profile' AND status='active' ORDER BY key",
    )?;
    let rows: Vec<(String, String, Option<String>, Option<i64>)> =
        st.query_map([], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?)))?.collect::<rusqlite::Result<_>>()?;
    let mut g = String::from(
        "What the Second Brain currently believes about you. Correct it in your journal (\"Actually, ...\") or with `sb memory retract <id>`.\n\n",
    );
    for (k, c, d, b) in rows {
        g.push_str(&format!(
            "- **{k}**: {c}{}{}\n",
            d.map(|d| format!(" (since {d})")).unwrap_or_default(),
            source_link(&brain.conn, b)?
        ));
    }
    Ok(g)
}

/// Regenerate every dirty note. Returns how many files changed.
pub fn regenerate_dirty(brain: &Brain) -> Result<usize> {
    let ids: Vec<i64> = brain
        .conn
        .prepare("SELECT id FROM entities WHERE dirty=1 AND status='active'")?
        .query_map([], |r| r.get(0))?
        .collect::<rusqlite::Result<_>>()?;
    let mut written = 0;
    for id in ids {
        let (path, fm, title, body) = render_entity(brain, id)?;
        // Restore a note that was archived earlier (keeps the user's own text).
        let archived = brain.vault().join("archive").join(path.file_name().unwrap_or_default());
        if !path.exists() && archived.exists() {
            let _ = std::fs::rename(&archived, &path);
        }
        if write_region(&path, &fm, &title, &body)? {
            written += 1;
        }
        brain.conn.execute("UPDATE entities SET dirty=0 WHERE id=?1", params![id])?;
    }
    if crate::db::kv_get(&brain.conn, "profile_dirty")?.as_deref() == Some("1") {
        let path = brain.vault().join("summaries/Profile.md");
        if write_region(&path, "type: profile\n", "Profile", &render_profile(brain)?)? {
            written += 1;
        }
        crate::db::kv_set(&brain.conn, "profile_dirty", "0")?;
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preserves_user_text() {
        let d = tempfile::tempdir().unwrap();
        let p = d.path().join("n.md");
        write_region(&p, "type: concept\n", "X", "gen 1").unwrap();
        let mut t = std::fs::read_to_string(&p).unwrap();
        t.push_str("\nMy own notes.\n");
        std::fs::write(&p, &t).unwrap();
        assert!(write_region(&p, "type: concept\n", "X", "gen 2").unwrap());
        let t = std::fs::read_to_string(&p).unwrap();
        assert!(t.contains("gen 2") && !t.contains("gen 1") && t.contains("My own notes."));
        assert!(!write_region(&p, "type: concept\n", "X", "gen 2").unwrap());
    }
}
